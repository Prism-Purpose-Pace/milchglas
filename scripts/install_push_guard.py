"""Install the pre-push entry that reads every ref a push transfers.

pre-commit reads git's pre-push stdin itself and hands hooks at most the first ref with new
commits; for a push whose refs carry no new commit it runs no hook at all. A branch or tag
name, refs 2..n of a multi-ref push and an annotated tag's own message therefore reach the
remote unscanned by a hook pre-commit dispatches. pre-commit's generated .git/hooks/pre-push
does run .git/hooks/pre-push.legacy first, with git's argv (remote name, remote URL) and
git's full stdin, and a non-zero exit stops the push. This script writes that file: a small
Python shim that runs `check_public_tree.py --pre-push-refs <remote name> <remote URL>`.

    uv run --script scripts/install_push_guard.py          install (once per clone)
    uv run --script scripts/install_push_guard.py --check  the commit-stage preflight

The shim lives in the clone's hooks directory, so it is per clone and unversioned; --check
(a pre-commit hook at the commit stage) fails when a maintainer clone lacks it, when it is not
executable or differs from what this script writes, when .git/hooks/pre-push is not
pre-commit's, or when that hook no longer passes --hook-dir: pre-commit's `_run_legacy` skips
the legacy hook without it (`# git 2.54+ hooks`, the git config hook call), and the route would
go silent instead of failing. That failure is the cue to move the guard to its own git config
hook (`hook.<name>.event = pre-push`, git 2.54+), which git also hands every ref. On any git,
pre-commit's classic hook passes the flag. A maintainer clone is
one where the public-tree guard finds a denylist or the main checkout holds `.claude/.git`;
anywhere else (a public contributor, who pushes to a fork) --check exits 0 with a notice.

Exit codes: 0 done or nothing to enforce, 1 the guard would not run (or a failing git).
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path
from typing import TYPE_CHECKING

# Sibling script (this directory is sys.path[0] when run as a script): one denylist lookup
# and one git wrapper for the guard and its installer.
from check_public_tree import (
    DEFAULT_DENYLIST,
    DenylistError,
    GitError,
    git_out,
    load_denylist,
    main_checkout_denylist,
)

if TYPE_CHECKING:
    from collections.abc import Sequence

SHIM_NAME = "pre-push.legacy"
PRE_COMMIT_MARKER = "File generated by pre-commit"
# pre-commit's `_run_legacy` runs pre-push.legacy only when the hook passes this (hook-tmpl).
HOOK_DIR_FLAG = "--hook-dir"
NO_HOOK_DIR = f"no longer passes {HOOK_DIR_FLAG}"
INSTALL_COMMAND = "uv run --script scripts/install_push_guard.py"
SHIM = """#!/usr/bin/env python3
# Written by scripts/install_push_guard.py. git runs this (through pre-commit's pre-push hook)
# with the remote name and URL as argv and one line per pushed ref on stdin. Do not edit:
# the installer's --check compares this file byte for byte.
import os
import shutil
import subprocess
import sys


def refuse(why):
    print("push guard: " + why + ", refusing the push", file=sys.stderr)
    sys.exit(1)


if shutil.which("uv") is None:
    refuse("uv not found")
try:
    top = subprocess.run(
        ["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True
    ).stdout.strip()
except OSError:
    top = ""
script = os.path.join(top, "scripts", "check_public_tree.py")
if not top or not os.path.isfile(script):
    refuse("scripts/check_public_tree.py not found")
command = ["uv", "run", "--script", script, "--pre-push-refs"] + sys.argv[1:3]
sys.exit(subprocess.run(command).returncode)
"""


def hooks_dir() -> Path:
    common = git_out("rev-parse", "--path-format=absolute", "--git-common-dir")
    return Path(common.decode().strip()) / "hooks"


def pre_push_problem(pre_push: Path) -> str | None:
    """Why pre-commit's pre-push hook would not run pre-push.legacy, or None."""
    text = pre_push.read_text(encoding="utf-8", errors="replace") if pre_push.is_file() else ""
    if PRE_COMMIT_MARKER not in text:
        return f"{pre_push} is not pre-commit's hook: run `pre-commit install` first"
    if HOOK_DIR_FLAG not in text:
        return (
            f"{pre_push} {NO_HOOK_DIR}, so pre-commit skips {SHIM_NAME}: "
            "move the guard to a git config hook (TOOLING.md)"
        )
    return None


def is_maintainer_clone(hooks: Path) -> bool:
    """Whether the guard finds a denylist here, or the main checkout holds the private repo."""
    denylist = DEFAULT_DENYLIST
    if not denylist.is_file():
        denylist = main_checkout_denylist() or denylist
    try:
        if load_denylist(denylist, os.environ) is not None:
            return True
    except DenylistError:
        return True  # a denylist exists; the guard itself reports that it is broken
    return (hooks.parent.parent / ".claude" / ".git").exists()


def problem(hooks: Path) -> str | None:
    """Why the push guard would not run in this clone, or None."""
    if (why := pre_push_problem(hooks / "pre-push")) is not None:
        return why
    shim = hooks / SHIM_NAME
    if not shim.is_file():
        return f"{SHIM_NAME} is missing: run `{INSTALL_COMMAND}`"
    if not os.access(shim, os.X_OK):
        return f"{SHIM_NAME} is not executable: run `{INSTALL_COMMAND}`"
    if shim.read_text(encoding="utf-8", errors="replace") != SHIM:
        return f"{SHIM_NAME} differs from the installer's: run `{INSTALL_COMMAND}`"
    return None


def check(hooks: Path) -> int:
    if not is_maintainer_clone(hooks):
        print("install-push-guard: no maintainer denylist here, check skipped", file=sys.stderr)
        return 0
    why = problem(hooks)
    if why is not None:
        print(f"install-push-guard: {why}", file=sys.stderr)
        return 1
    print(f"install-push-guard: {SHIM_NAME} installed", file=sys.stderr)
    return 0


def install(hooks: Path) -> int:
    if (why := pre_push_problem(hooks / "pre-push")) is not None:
        print(f"install-push-guard: {why}", file=sys.stderr)
        return 1
    shim = hooks / SHIM_NAME
    shim.write_text(SHIM, encoding="utf-8")
    shim.chmod(0o755)
    print(f"install-push-guard: wrote {shim}", file=sys.stderr)
    return 0


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Install the pre-push entry that scans every ref.")
    parser.add_argument(
        "--check",
        action="store_true",
        help="the commit-stage preflight: exit 1 when a maintainer clone would push unguarded",
    )
    args = parser.parse_args(argv)
    try:
        hooks = hooks_dir()
        return check(hooks) if args.check else install(hooks)
    except GitError as exc:
        print(f"install-push-guard: {exc}, refusing", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
