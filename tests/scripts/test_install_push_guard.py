"""install_push_guard.py: the pre-push.legacy entry that reads every ref of a push."""

import os
from collections.abc import Callable
from pathlib import Path

import pytest

import check_public_tree as cpt
import install_push_guard as ipg
from tests.scripts.test_check_public_tree import _git

REPO = Path(__file__).resolve().parents[2]
PRE_COMMIT_HOOK = "#!/usr/bin/env bash\n# File generated by pre-commit: https://pre-commit.com\n"
REAL_GIT_VERSION = ipg.git_version  # the autouse fixture below replaces the module attribute


@pytest.fixture(autouse=True)
def old_git(monkeypatch: pytest.MonkeyPatch) -> None:
    # The machine's git must not decide these tests; the 2.54 case sets its own version.
    monkeypatch.setattr(ipg, "git_version", lambda: (2, 50))


@pytest.fixture
def clone(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """A maintainer clone (denylist in the environment) with pre-commit's pre-push hook."""
    repo = tmp_path / "repo"
    repo.mkdir()
    _git(repo, "init", "-q", "-b", "main")
    hooks = repo / ".git/hooks"
    hooks.mkdir(exist_ok=True)
    (hooks / "pre-push").write_text(PRE_COMMIT_HOOK, encoding="utf-8")
    monkeypatch.chdir(repo)
    monkeypatch.setenv("PUBLIC_DENYLIST", "secretproject")
    return repo


def _shim(repo: Path) -> Path:
    return repo / ".git/hooks/pre-push.legacy"


def test_install_writes_an_executable_shim_and_check_passes(clone: Path) -> None:
    assert ipg.main([]) == 0
    assert _shim(clone).read_text(encoding="utf-8") == ipg.SHIM
    assert os.access(_shim(clone), os.X_OK)
    assert ipg.main(["--check"]) == 0


def test_install_twice_leaves_one_working_shim(clone: Path) -> None:
    assert ipg.main([]) == 0
    _shim(clone).write_text("drifted\n", encoding="utf-8")
    assert ipg.main([]) == 0
    assert ipg.main(["--check"]) == 0


def test_install_refuses_when_pre_push_is_not_pre_commits(
    clone: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    (clone / ".git/hooks/pre-push").write_text("#!/bin/sh\nexit 0\n", encoding="utf-8")
    assert ipg.main([]) == 1
    assert "run `pre-commit install` first" in capsys.readouterr().err
    assert not _shim(clone).exists()


def test_install_refuses_when_there_is_no_pre_push_hook(
    clone: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    (clone / ".git/hooks/pre-push").unlink()
    assert ipg.main([]) == 1
    assert "run `pre-commit install` first" in capsys.readouterr().err
    assert not _shim(clone).exists()


def _delete_shim(clone: Path) -> None:
    _shim(clone).unlink()


def _make_not_executable(clone: Path) -> None:
    _shim(clone).chmod(0o644)


def _drift(clone: Path) -> None:
    _shim(clone).write_text(ipg.SHIM + "# edited\n", encoding="utf-8")


def _foreign_pre_push(clone: Path) -> None:
    (clone / ".git/hooks/pre-push").write_text("#!/bin/sh\nexit 0\n", encoding="utf-8")


def _remove_pre_push(clone: Path) -> None:
    (clone / ".git/hooks/pre-push").unlink()


FAILURES = [
    (_delete_shim, "pre-push.legacy is missing"),
    (_make_not_executable, "pre-push.legacy is not executable"),
    (_drift, "pre-push.legacy differs from the installer's"),
    (_foreign_pre_push, "is not pre-commit's hook: run `pre-commit install` first"),
    (_remove_pre_push, "is not pre-commit's hook: run `pre-commit install` first"),
]


@pytest.mark.parametrize(
    ("break_it", "message"),
    FAILURES,
    ids=["missing", "not-executable", "drifted", "foreign", "none"],
)
def test_check_fails_in_a_maintainer_clone_with_one_actionable_line(
    clone: Path,
    capsys: pytest.CaptureFixture[str],
    break_it: Callable[[Path], None],
    message: str,
) -> None:
    assert ipg.main([]) == 0
    capsys.readouterr()
    break_it(clone)
    assert ipg.main(["--check"]) == 1
    err = capsys.readouterr().err
    assert len(err.splitlines()) == 1
    assert message in err
    assert "install_push_guard.py" in err or "pre-commit install" in err


@pytest.mark.usefixtures("clone")
@pytest.mark.parametrize("version", [(2, 54), (2, 60), (3, 0)])
def test_check_fails_on_git_2_54_or_later(
    monkeypatch: pytest.MonkeyPatch,
    capsys: pytest.CaptureFixture[str],
    version: tuple[int, int],
) -> None:
    assert ipg.main([]) == 0  # a good install, only the git version is wrong
    capsys.readouterr()
    monkeypatch.setattr(ipg, "git_version", lambda: version)
    assert ipg.main(["--check"]) == 1
    err = capsys.readouterr().err
    assert len(err.splitlines()) == 1
    assert "2.54" in err
    assert "pre-push.legacy" in err


@pytest.mark.usefixtures("clone")
def test_check_passes_on_git_2_53(monkeypatch: pytest.MonkeyPatch) -> None:
    assert ipg.main([]) == 0
    monkeypatch.setattr(ipg, "git_version", lambda: (2, 53))
    assert ipg.main(["--check"]) == 0


@pytest.mark.parametrize(
    ("text", "version"),
    [
        ("git version 2.50.1 (Apple Git-155)\n", (2, 50)),
        ("git version 2.54.0\n", (2, 54)),
        ("git version 2.54.0.windows.1\n", (2, 54)),
        ("git version 3.0.0\n", (3, 0)),
    ],
)
def test_git_version_is_read_from_git_version_output(
    text: str, version: tuple[int, int], monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.setattr(ipg, "git_out", lambda *_args: text.encode())
    assert REAL_GIT_VERSION() == version


def test_unreadable_git_version_fails_closed(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(ipg, "git_out", lambda *_args: b"not a version\n")
    with pytest.raises(cpt.GitError):
        REAL_GIT_VERSION()


def test_check_passes_in_a_contributor_clone_with_a_notice(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    # No denylist, no private nested repo: a public contributor never runs the maintainer
    # guard, so a missing shim must not block their commit.
    _git(tmp_path, "init", "-q", "-b", "main")
    monkeypatch.chdir(tmp_path)
    monkeypatch.delenv("PUBLIC_DENYLIST", raising=False)
    assert ipg.main(["--check"]) == 0
    err = capsys.readouterr().err
    assert len(err.splitlines()) == 1
    assert "skipped" in err
    assert not _shim(tmp_path).exists()


def test_a_private_nested_repo_marks_a_maintainer_clone(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    _git(tmp_path, "init", "-q", "-b", "main")
    (tmp_path / ".git/hooks/pre-push").write_text(PRE_COMMIT_HOOK, encoding="utf-8")
    monkeypatch.chdir(tmp_path)
    monkeypatch.delenv("PUBLIC_DENYLIST", raising=False)
    assert ipg.main(["--check"]) == 0  # contributor: nothing to enforce
    (tmp_path / ".claude/.git").mkdir(parents=True)
    assert ipg.main(["--check"]) == 1  # maintainer: the shim is missing


def test_a_denylist_file_marks_a_maintainer_clone(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    _git(tmp_path, "init", "-q", "-b", "main")
    (tmp_path / ".git/hooks/pre-push").write_text(PRE_COMMIT_HOOK, encoding="utf-8")
    monkeypatch.chdir(tmp_path)
    monkeypatch.delenv("PUBLIC_DENYLIST", raising=False)
    deny = tmp_path / ".claude/context/public-denylist.txt"
    deny.parent.mkdir(parents=True)
    deny.write_text("secretproject\n", encoding="utf-8")
    assert ipg.main(["--check"]) == 1


def test_a_linked_worktree_finds_the_shim_in_the_main_checkouts_hooks(
    clone: Path, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    _git(clone, "commit", "-q", "--allow-empty", "-m", "root")
    _git(clone, "worktree", "add", "-q", "--detach", str(tmp_path / "wt"))
    monkeypatch.chdir(tmp_path / "wt")
    assert ipg.main([]) == 0
    assert _shim(clone).read_text(encoding="utf-8") == ipg.SHIM
    assert ipg.main(["--check"]) == 0


def test_shim_is_valid_python_that_forwards_argv_and_stdin() -> None:
    compile(ipg.SHIM, "pre-push.legacy", "exec")
    assert ipg.SHIM.startswith("#!/usr/bin/env python3\n")
    assert '"--pre-push-refs"' in ipg.SHIM
    assert "sys.argv[1:3]" in ipg.SHIM


def test_commit_stage_preflight_is_wired_in_the_pre_commit_config() -> None:
    config = (REPO / ".pre-commit-config.yaml").read_text(encoding="utf-8")
    assert "- id: check-push-guard-installed\n" in config
    block = config.split("- id: check-push-guard-installed\n", 1)[-1].split("- id:", 1)[0]
    assert "entry: uv run --script scripts/install_push_guard.py --check\n" in block
    assert "always_run: true" in block
    assert "pass_filenames: false" in block
    assert "verbose: true" in block
    assert "stages:" not in block  # default_stages is the pre-commit stage


def test_first_ref_fallback_stays_wired_next_to_the_legacy_entry() -> None:
    config = (REPO / ".pre-commit-config.yaml").read_text(encoding="utf-8")
    block = config.split("- id: check-public-tree-history", 1)[-1].split("- id:", 1)[0]
    assert "entry: uv run --script scripts/check_public_tree.py --pre-push\n" in block


def test_docs_name_the_install_step_and_the_legacy_entry() -> None:
    install = "uv run --script scripts/install_push_guard.py"
    contributing = (REPO / "CONTRIBUTING.md").read_text(encoding="utf-8")
    assert f"pre-commit install --install-hooks\n{install}\n" in contributing
    tooling = (REPO / "TOOLING.md").read_text(encoding="utf-8")
    assert "pre-push.legacy" in tooling
    assert "--pre-push-refs" in tooling
    docstring = (REPO / "scripts/check_public_tree.py").read_text(encoding="utf-8")
    assert "--pre-push-refs" in docstring.split('"""', 2)[1]


