def test_a_failing_git_is_refused_in_one_line(
    monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    def failing_git(*_args: str) -> bytes:
        msg = "git rev-parse failed"
        raise cpt.GitError(msg)

    monkeypatch.setattr(ipg, "git_out", failing_git)
    assert ipg.main(["--check"]) == 1
    assert capsys.readouterr().err == "install-push-guard: git rev-parse failed, refusing\n"
